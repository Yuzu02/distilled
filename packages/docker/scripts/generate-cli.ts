/**
 * Docker CLI canonical JSON metadata -> typed Effect Schema and facade.
 *
 * The upstream Go/Cobra-generated metadata describes syntax and flags, not Engine API input
 * payloads or response bodies. Output schemas are therefore NOT invented by
 * this generator. The /cli entrypoint may reuse a known Engine API response
 * schema for a compatible JSON command, e.g. container inspect.
 */
import { join } from "node:path";
import { camel, oneLine, q, RESERVED, upperFirst } from "@distilled.cloud/dev/codegen/naming";
import { resolveSpecPath } from "@distilled.cloud/dev/codegen/spec-path";
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import * as A from "effect/Array";
import * as Console from "effect/Console";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Option from "effect/Option";
import * as Order from "effect/Order";
import * as R from "effect/Record";
import * as Schema from "effect/Schema";
import * as Str from "effect/String";
import { decodeCliReference, type CliOption, type CliValueType } from "./cli-reference.ts";
import { cliSources } from "./cli-specs.ts";
import { minimumArgs } from "./cli-usage.ts";

const root = join(import.meta.dirname, "..");
const encodeJson = Schema.encodeUnknownEffect(Schema.fromJsonString(Schema.Json));

class DockerCliGenerationError extends Schema.TaggedError<DockerCliGenerationError>()(
  "DockerCliGenerationError",
  {
    source: Schema.String,
    reason: Schema.Literals([
      "conflicting-revision",
      "missing-spec",
      "unexpected-command",
      "conflicting-property",
    ]),
  },
) {}
/** Exhaustively map official, Schema-validated Docker flag kinds to codecs. */
const cliValueSchemas = {
  bool: "Schema.Boolean",
  decimal: "Schema.Finite",
  float: "Schema.Finite",
  int: "Schema.Int",
  uint: "Schema.Int.check(Schema.isGreaterThanOrEqualTo(0))",
  uint16: "Schema.Int.check(Schema.isBetween({ minimum: 0, maximum: 65535 }))",
  uint32: "Schema.Int.check(Schema.isBetween({ minimum: 0, maximum: 4294967295 }))",
  int64: "Schema.Union([Schema.Int, Schema.String])",
  uint64: "Schema.Union([Schema.Int.check(Schema.isGreaterThanOrEqualTo(0)), Schema.String])",
  bytes: "Schema.Union([Schema.Int, Schema.String])",
  map: "Schema.Record(Schema.String, Schema.String)",
  stringToString: "Schema.Record(Schema.String, Schema.String)",
  filter:
    "Schema.Union([Schema.Array(Schema.String), Schema.Record(Schema.String, Schema.String)])",
  list: "Schema.Array(Schema.String)",
  ipNetSlice: "Schema.Array(Schema.String)",
  ipSlice: "Schema.Array(Schema.String)",
  stringArray: "Schema.Array(Schema.String)",
  stringSlice: "Schema.Array(Schema.String)",
  mount: "Schema.Union([Schema.String, Schema.Array(Schema.String)])",
  config: "Schema.Union([Schema.String, Schema.Array(Schema.String)])",
  secret: "Schema.Union([Schema.String, Schema.Array(Schema.String)])",
  "external-ca": "Schema.Union([Schema.String, Schema.Array(Schema.String)])",
  ulimit: "Schema.Union([Schema.String, Schema.Array(Schema.String)])",
  command: "Schema.String",
  "credential-spec": "Schema.String",
  "node-addr": "Schema.String",
  port: "Schema.String",
  pref: "Schema.String",
  duration: "Schema.String",
  "gpu-request": "Schema.String",
  ip: "Schema.String",
  network: "Schema.String",
  string: "Schema.String",
  umask: "Schema.String",
  "pem-file": "Schema.String",
} as const satisfies Record<CliValueType, string>;

const schemaFor = (type: CliValueType): string => cliValueSchemas[type];

export const generateCli = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const sources = yield* cliSources;
  let revisions = R.empty<string, string>();
  for (const source of sources) {
    const repository = `${source.owner}/${source.repo}`;
    const previous = R.get(revisions, repository);
    if (Option.isSome(previous) && previous.value !== source.revision) {
      return yield* Effect.fail(
        new DockerCliGenerationError({ source: repository, reason: "conflicting-revision" }),
      );
    }
    revisions = R.set(revisions, repository, source.revision);
  }
  const revisionsJson = yield* encodeJson(
    R.fromEntries(A.sortWith(R.toEntries(revisions), ([name]) => name, Order.String)),
  );
  const output: string[] = [
    "// AUTO-GENERATED by scripts/generate-cli.ts from Docker's pinned CLI spec mirror.",
    "// Do not edit by hand. Re-run pnpm generate docker.",
    'import * as Schema from "effect/Schema";',
    'import { invoke, invokeStream, type CommandExecutionOptions, type CommandSpec } from "./runtime.ts";',
    "",
    "/** Exact upstream revisions used for the published Docker CLI SDK. */",
    `export const dockerCliSourceRevisions = ${revisionsJson} as const;`,
    "",
  ];

  for (const source of sources) {
    const file = yield* Effect.try({
      try: () =>
        resolveSpecPath(root, `specs/spec-mirror-docker/specs/cli/commands/${source.name}.json`),
      catch: () => new DockerCliGenerationError({ source: source.name, reason: "missing-spec" }),
    });
    const spec = yield* decodeCliReference(yield* fs.readFileString(file));
    const command = Str.split(spec.command, " ");
    if (command[0] !== "docker" || spec.usage === undefined) {
      return yield* new DockerCliGenerationError({
        source: spec.command,
        reason: "unexpected-command",
      });
    }
    const arity = yield* minimumArgs(spec.usage, spec.command);
    const name = camel(source.name);
    const type = upperFirst(name);
    // Top-level commands (e.g. `docker run`) share a barrel with transport
    // helpers such as `run`; prefix them instead of shadowing runtime APIs.
    const operation = command.length === 2 || RESERVED.has(name) ? `docker${type}` : name;
    const options = [...(spec.inherited_options ?? []), ...(spec.options ?? [])];
    let byName = R.empty<string, CliOption>();
    for (const option of options) {
      if (option.hidden === true) continue;
      const property = camel(option.option);
      const previous = R.get(byName, property);
      if (Option.isSome(previous) && previous.value.option !== option.option) {
        return yield* Effect.fail(
          new DockerCliGenerationError({
            source: `${spec.command}.${property}`,
            reason: "conflicting-property",
          }),
        );
      }
      byName = R.set(byName, property, option);
    }
    const sortedOptions = A.sortWith(R.toEntries(byName), ([name]) => name, Order.String);

    output.push(`/** Flags for ${oneLine(spec.command)} (${oneLine(spec.usage)}). */`);
    output.push(`export const ${type}Flags = Schema.Struct({`);
    for (const [property, option] of sortedOptions) {
      const kind = schemaFor(option.value_type);
      output.push(`  ${q(property)}: Schema.optional(${kind}),`);
    }
    output.push("});");
    output.push(`export type ${type}Flags = Schema.Schema.Type<typeof ${type}Flags>;`);
    output.push(`export const ${type}InputSchema = Schema.Struct({`);
    output.push(`  flags: Schema.optional(${type}Flags),`);
    output.push(
      arity > 0
        ? `  args: Schema.TupleWithRest(Schema.Tuple([${A.makeBy(arity, () => "Schema.String").join(", ")}]), [Schema.String]),`
        : "  args: Schema.optional(Schema.Array(Schema.String)),",
    );
    output.push("  context: Schema.optional(Schema.String),");
    output.push("});");
    output.push(`export type ${type}Input = Schema.Schema.Type<typeof ${type}InputSchema>;`);
    output.push(`export const ${name}Spec = {`);
    output.push(`  command: ${yield* encodeJson(A.drop(command, 1))},`);
    output.push(`  usage: ${q(spec.usage)},`);
    output.push(`  minimumArgs: ${arity},`);
    output.push("  flags: {");
    for (const [property, option] of sortedOptions) {
      const metadata = {
        name: option.option,
        type: option.value_type,
        ...(option.shorthand ? { shorthand: option.shorthand } : {}),
        ...(option.default_value !== undefined ? { defaultValue: option.default_value } : {}),
        ...(option.description ? { description: option.description } : {}),
        ...(option.min_api_version ? { minApiVersion: option.min_api_version } : {}),
        ...(option.os_type ? { osType: option.os_type } : {}),
        ...(option.deprecated ? { deprecated: true } : {}),
        ...(option.experimental ? { experimental: true } : {}),
      };
      output.push(`    ${q(property)}: ${yield* encodeJson(metadata)},`);
    }
    output.push("  },");
    output.push("} as const satisfies CommandSpec;");
    output.push(
      `export const ${operation} = (input: ${type}Input, options?: CommandExecutionOptions) => invoke(${name}Spec, ${type}InputSchema, input, options);`,
      "",
    );
    output.push(
      `export const ${operation}Stream = (input: ${type}Input, options?: CommandExecutionOptions) => invokeStream(${name}Spec, ${type}InputSchema, input, options);`,
      "",
    );
  }

  yield* fs.writeFileString(join(root, "src", "cli", "generated.ts"), output.join("\n"));
  yield* Console.log(
    `generated ${sources.length} Docker CLI operations from the pinned JSON mirror`,
  );
});

if (import.meta.main) {
  generateCli.pipe(Effect.provide(NodeServices.layer), NodeRuntime.runMain);
}
